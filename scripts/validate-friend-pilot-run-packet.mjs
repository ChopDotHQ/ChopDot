#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const repoRoot = process.cwd();
const packetPath = path.join(repoRoot, 'docs/chopdot-dot/friend-pilot-run-packet-2026-06-21.md');

const requiredSections = [
  '## Local Setup',
  '## Entry Links',
  '## Five Questions Before Any Click',
  '## Required Evidence',
  '## Unsafe Assumptions That Fail The Scenario',
  '## Recording Results',
  '## Fast Verification Before Running',
];

const requiredScenarios = [
  'Group expense',
  'Savings circle',
  'Emergency pot',
  'Community fund',
  'Capture / Pay / Confirm',
  'Onboarding',
];

const requiredPeople = [
  'Leo',
  'Nina',
  'Omar',
  'Mina',
  'Casey',
  'Riley',
  'Taylor',
  'Jordan',
  'Sam',
  'Alex',
  'Priya',
];

const requiredPhrases = [
  'Use separate devices or separate browser profiles',
  'Do not role-switch on one shared screen',
  'What would be unsafe to assume from this screen?',
  'participant pseudonyms only',
  'first interpretation before coaching',
  'coaching needed: `none`, `minor`, or `blocking`',
  'money-model check',
  'receipt/return check',
  'receipt screenshot if closeout is reached',
  'ChopDot holds or protects the money',
  '`Mark paid` means receiver confirmation',
  'approval means payment happened',
  'token or webhook evidence confirms receipt',
  'checkout evidence can support a payment claim but',
  'live `.dot` or host-native proof is complete today',
  'Capture/pay/confirm should use links generated by the app during the pilot',
  'friend-pilot-results-ledger-2026-06-20.md',
  'Do not change a scenario to `pass` unless every evidence field is complete',
  'A pass requires `Coaching needed: none`',
  'npm run validate:friend-pilot',
  'npm run validate:use-case-9',
];

function main() {
  const failures = [];

  if (!fs.existsSync(packetPath)) {
    console.error(`Missing friend-pilot run packet: ${packetPath}`);
    process.exit(1);
  }

  const content = fs.readFileSync(packetPath, 'utf8');

  for (const section of requiredSections) {
    if (!content.includes(section)) failures.push(`Missing section: ${section}`);
  }

  for (const scenario of requiredScenarios) {
    if (!content.includes(scenario)) failures.push(`Missing scenario: ${scenario}`);
  }

  for (const person of requiredPeople) {
    if (!content.includes(person)) failures.push(`Missing pilot person: ${person}`);
  }

  for (const phrase of requiredPhrases) {
    if (!content.includes(phrase)) failures.push(`Missing required phrase: ${phrase}`);
  }

  const nativeLinkCount = (content.match(/chopdot-dot-native=1/g) ?? []).length;
  if (nativeLinkCount < 15) {
    failures.push(`Expected at least 15 native entry links; found ${nativeLinkCount}.`);
  }

  const localhostCount = (content.match(/http:\/\/127\.0\.0\.1:5173\/pots/g) ?? []).length;
  if (localhostCount < 16) {
    failures.push(`Expected local /pots links for pilot entry; found ${localhostCount}.`);
  }

  if (failures.length > 0) {
    console.error('\n❌ Friend-pilot run packet validation FAILED\n');
    for (const failure of failures) console.error(`- ${failure}`);
    console.error('\nFix: update docs/chopdot-dot/friend-pilot-run-packet-2026-06-21.md.\n');
    process.exit(1);
  }

  console.log('✅ Friend-pilot run packet OK — routes, evidence fields, and fail conditions are present');
}

main();
