#!/usr/bin/env node
/**
 * Generate a concrete friend-pilot run packet with real links for one session.
 *
 * This does not mark any scenario as passed. It only removes setup friction so
 * real participant evidence can be collected without editing docs by hand.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function argValue(name) {
  const flag = `--${name}`;
  const index = process.argv.indexOf(flag);
  if (index >= 0 && process.argv[index + 1]) return process.argv[index + 1];
  return undefined;
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

function safeSlug(value) {
  return value.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '') || `friend-pilot-${today()}`;
}

const session = safeSlug(argValue('session') ?? process.env.FRIEND_PILOT_SESSION ?? `friend-pilot-${today()}`);
const baseUrl = (argValue('base-url') ?? process.env.FRIEND_PILOT_BASE_URL ?? 'http://127.0.0.1:5173').replace(/\/+$/, '');
const outputDir = path.join(repoRoot, 'artifacts/friend-pilot', session);
const outputPath = path.join(outputDir, 'run-sheet.md');

const scenarios = [
  {
    name: 'Group Expense',
    suffix: 'group',
    people: ['leo', 'nina', 'mina'],
    job: 'Split one shared expense, mark paid, confirm received, and explain what is still open.',
  },
  {
    name: 'Savings Circle',
    suffix: 'savings',
    people: ['leo', 'nina', 'omar', 'mina'],
    job: 'Run one savings round, handle one delay, and explain whether the round can close.',
  },
  {
    name: 'Emergency Pot',
    suffix: 'emergency',
    people: ['casey', 'riley', 'taylor', 'jordan'],
    job: 'Coordinate urgent help while keeping private details and receipt redaction understandable.',
  },
  {
    name: 'Community Fund',
    suffix: 'community',
    people: ['sam', 'alex', 'priya', 'jordan'],
    job: 'Request, approve, record, and confirm a shared fund release without treating approval as payment.',
  },
  {
    name: 'Capture / Pay / Confirm',
    suffix: 'capture',
    people: ['leo', 'mina', 'nina'],
    job: 'Record a checkout payment moment, send app-generated pay/confirm links, and prove checkout evidence does not bypass receiver confirmation.',
    usesGeneratedLinks: true,
  },
  {
    name: 'Onboarding / First Entry',
    suffix: '',
    people: ['new-user'],
    job: 'Start or join without believing a wallet is required for the group record.',
  },
];

function linkFor(scenario, person) {
  if (scenario.name === 'Onboarding / First Entry') return `${baseUrl}/pots`;
  if (scenario.usesGeneratedLinks) return `${baseUrl}/pots`;
  const params = new URLSearchParams({
    'chopdot-dot-native': '1',
    person,
    'chopdot-dot-session': `${session}-${scenario.suffix}`,
  });
  return `${baseUrl}/pots?${params.toString()}`;
}

function scenarioTable() {
  const rows = [];
  for (const scenario of scenarios) {
    for (const person of scenario.people) {
      rows.push(`| ${scenario.name} | ${person} | ${linkFor(scenario, person)} |`);
    }
  }
  return rows.join('\n');
}

function ledgerTemplateRows() {
  return scenarios.map((scenario) => [
    `### ${scenario.name}`,
    '',
    '```text',
    `Scenario: ${scenario.name}`,
    `Session: ${session}`,
    'Date:',
    'Facilitator:',
    'Participants:',
    'Devices:',
    `Route: ${scenario.people.map((person) => `${person}=${linkFor(scenario, person)}`).join(' ; ')}`,
    'First user interpretation:',
    'Coaching needed: none/minor/blocking',
    'Action completed:',
    'What blocked the group:',
    'Unsafe assumption observed:',
    'Money-model check:',
    'Receipt/return understood: yes/no',
    'Screenshot refs:',
    'Pass/fail:',
    'Required product fix:',
    'Promotion decision:',
    '```',
    '',
  ].join('\n')).join('\n');
}

const body = `# ChopDot Friend Pilot Run Sheet

Status: \`ready-to-run\`
Generated: ${new Date().toISOString()}
Session: \`${session}\`
Base URL: \`${baseUrl}\`

## Start

Run the app:

\`\`\`bash
npm run dev
\`\`\`

Use separate devices or separate browser profiles. Do not role-switch on one shared screen for evidence.

## Links

| Scenario | Person | Link |
| --- | --- | --- |
${scenarioTable()}

For **Capture / Pay / Confirm**, start at \`${baseUrl}/pots\`, open or create a
capture-capable expense pot, then use links generated by the app during the
pilot. Do not handwrite \`/spend\`, \`/pay\`, or \`/confirm\` tokens.

## What Each Scenario Is Trying To Prove

${scenarios.map((scenario) => `- **${scenario.name}:** ${scenario.job}`).join('\n')}

## Ask Before Any Click

1. What is this group trying to finish?
2. What is your next step?
3. Who is the group waiting on?
4. What would be unsafe to assume from this screen?
5. What record would you trust later?

Do not coach before the participant answers.

## Unsafe Assumptions That Fail The Scenario

- ChopDot holds or protects the money.
- \`Mark paid\` means receiver confirmation.
- Approval means payment happened.
- Token, webhook, or checkout evidence confirms receipt.
- Release record means the recipient received money.
- Closeout means every open item was paid.
- Emergency details are public by default.
- Static \`.dot\` publish means full host-native proof is complete.

## Evidence Checklist

- participant pseudonyms only;
- device or browser profile used;
- route used;
- first interpretation before coaching;
- coaching needed: \`none\`, \`minor\`, or \`blocking\`;
- action completed;
- blocker explanation;
- unsafe assumption check;
- money-model check in the participant's own words;
- screenshot after action;
- receipt or return-state explanation;
- receipt screenshot if closeout is reached;
- pass/fail decision;
- required product fix before promotion.

## Ledger Templates

Paste completed sections into:

\`\`\`text
docs/chopdot-dot/friend-pilot-results-ledger-2026-06-20.md
\`\`\`

${ledgerTemplateRows()}
`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(outputPath, body);

console.log(`Friend pilot session: ${session}`);
console.log(`Run sheet: ${outputPath}`);
