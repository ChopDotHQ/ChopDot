import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname,join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deriveStage4 } from './stage-4-lib.mjs';
const root=join(dirname(fileURLToPath(import.meta.url)),'..'),read=n=>JSON.parse(readFileSync(join(root,'product-schema',n),'utf8'));
const x=deriveStage4(read('semantic-core.json'),read('composition-graph.json'),read('frozen-baseline.json'));
const r=JSON.parse(readFileSync(join(root,'product-schema/generated/completeness-report.json'),'utf8'));
const p=JSON.parse(readFileSync(join(root,'product-schema/generated/gate-b-construction.json'),'utf8'));
assert.deepEqual(r,x.report);
assert.deepEqual(p,x.packet);
assert.equal(r.schema_status,'PASS');
assert.equal(p.gate.pre_gate_b_readiness,'READY_FOR_HUMAN_AUTHORIZATION');
assert.equal(p.authority_blockers.length,0);
assert.equal(p.product_decisions_required.length,0);
assert.ok(p.authority_recoveries.some(x=>x.id==='RECOVERY-J05-GOLDEN-01'));
for(const id of ['RESOLVED-EXPENSE-LOCK-01','RESOLVED-EXPENSE-REVIEW-01','RESOLVED-J05-ARTIFACT-01'])assert.ok(p.resolved_authority_interpretations.some(x=>x.id===id));
assert.ok(p.construction_requirements.some(x=>x.id==='REQ-J05-LOCK'));
assert.ok(p.construction_requirements.some(x=>x.id==='REQ-J06-REVIEW-RESET'));
console.log(JSON.stringify({stage:4,schema_status:r.schema_status,pre_gate_b_readiness:r.pre_gate_b_readiness,recoveries:p.authority_recoveries.map(x=>x.id),blockers:0,product_decisions:0,result:'PASS'},null,2));
